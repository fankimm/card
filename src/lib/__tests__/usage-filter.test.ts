import { describe, expect, it } from 'vitest';
import {
  초로,
  점심시간대,
  점심지원대상,
  취소상쇄,
  월별내역추리기,
  누락의심일찾기,
  type UsageItem,
} from '../usage-filter';

const 건 = (o: Partial<UsageItem> & { date: string; time: string }): any => ({
  confirmType: '승인',
  cardNumber: '9427',
  user: '김지환',
  fee: '12000',
  place: '진밀옥',
  ...o,
});

describe('초로', () => {
  it('시가 한 자리여도 제대로 센다', () => {
    // 문자열로 비교하면 '9:21:00' > '10:00:00' 이 참이 되어버린다.
    expect(초로('9:21:00')).toBe(9 * 3600 + 21 * 60);
    expect(초로('09:21:00')).toBe(9 * 3600 + 21 * 60);
    expect(초로('11:39:00')).toBeLessThan(초로('12:00:00'));
    expect(초로('9:21:00')).toBeLessThan(초로('10:00:00'));
  });

  it('초가 없어도 동작한다', () => {
    expect(초로('12:38')).toBe(12 * 3600 + 38 * 60);
  });
});

describe('점심시간대', () => {
  it.each([
    ['9:21:00', false],
    ['10:00:00', false],
    ['10:00:01', true],
    ['12:30:00', true],
    ['15:40:00', true],
    ['16:00:00', false],
    ['18:58:00', false],
  ])('%s → %s', (time, expected) => {
    expect(점심시간대(time)).toBe(expected);
  });

  // 2026-08-18 회귀: 시트가 시각을 Date 원문으로 돌려주면 초로()가 NaN이 된다.
  // 예전 부정형 판정('초<=10시 || 초>=16시 이면 탈락')은 NaN이 두 비교를 모두
  // 빠져나가 통과시켰고, 긍정형으로 바꾸자 전부 탈락해 프로덕션이 0원이 됐다.
  // 어느 쪽이 맞든 파싱 불가 값은 여기서 걸러진다는 걸 고정해 둔다.
  it('파싱 못 하는 시각은 통과시키지 않는다', () => {
    expect(점심시간대('Sat Dec 30 1899 12:11:00 GMT+0827 (한국 표준시)')).toBe(
      false
    );
    expect(점심시간대('')).toBe(false);
  });
});

describe('점심지원대상', () => {
  it('1회 한도 2만원까지', () => {
    expect(점심지원대상(건({ date: '2026-08-05', time: '12:00:00', fee: '20000' }))).toBe(true);
    expect(점심지원대상(건({ date: '2026-08-05', time: '12:00:00', fee: '20001' }))).toBe(false);
  });

  it('코어타임 밖이면 금액과 무관하게 제외', () => {
    expect(점심지원대상(건({ date: '2026-08-05', time: '9:21:00', fee: '9000' }))).toBe(false);
  });
});

describe('취소상쇄', () => {
  it('취소 1건이 같은 조건의 승인 1건만 지운다', () => {
    // 취소하고 바로 다시 긁은 날은 승인이 2건인데, 그중 하나만 상쇄돼야 한다.
    const items = [
      건({ date: '2026-08-05', time: '11:42:00', fee: '36000', place: '황태마을' }),
      건({ date: '2026-08-05', time: '11:43:00', fee: '36000', place: '황태마을', confirmType: '취소' }),
      건({ date: '2026-08-05', time: '11:44:00', fee: '36000', place: '황태마을' }),
    ];
    const out = 취소상쇄(items);
    expect(out).toHaveLength(1);
    expect(out[0].time).toBe('11:44:00');
  });

  it('취소가 없으면 원본 그대로', () => {
    const items = [건({ date: '2026-08-05', time: '12:00:00' })];
    expect(취소상쇄(items)).toHaveLength(1);
  });

  it('취소와 시각이 가까운 승인부터 지운다', () => {
    const items = [
      건({ date: '2026-08-05', time: '11:00:00', fee: '10000' }),
      건({ date: '2026-08-05', time: '14:00:00', fee: '10000' }),
      건({ date: '2026-08-05', time: '14:01:00', fee: '10000', confirmType: '취소' }),
    ];
    const out = 취소상쇄(items);
    expect(out).toHaveLength(1);
    expect(out[0].time).toBe('11:00:00');
  });
});

describe('월별내역추리기', () => {
  const all = [
    건({ date: '2026-07-30', time: '12:00:00', fee: '10000' }),
    건({ date: '2026-08-05', time: '12:11:00', fee: '14000' }),
    건({ date: '2026-08-07', time: '9:21:00', fee: '9000' }), // 코어타임 밖
    건({ date: '2026-08-08', time: '12:00:00', fee: '30000' }), // 한도 초과
    건({ date: '2026-08-06', time: '11:36:00', fee: '13000', cardNumber: '8713' }), // 옛 카드
    건({ date: '2026-08-05', time: '12:35:00', fee: '15000', user: '홍동수', cardNumber: '6522' }),
  ];

  it('내 것 + 해당 월 + 지원 대상만, 시간순으로', () => {
    const out = 월별내역추리기(all, '김지환', '9427', '2026-08-18');
    expect(out.map((i) => i.date)).toEqual(['2026-08-05']);
  });

  it('옛 카드를 함께 주면 그 내역도 잡힌다', () => {
    const out = 월별내역추리기(all, '김지환', '9427,8713', '2026-08-18');
    expect(out.map((i) => i.date)).toEqual(['2026-08-05', '2026-08-06']);
  });

  it('마스킹된 이름도 같은 사람으로 본다', () => {
    const out = 월별내역추리기(
      [건({ date: '2026-08-05', time: '12:00:00', user: '김*환' })],
      '김지환',
      '9427',
      '2026-08-18'
    );
    expect(out).toHaveLength(1);
  });
});

describe('누락의심일찾기', () => {
  it('출근했는데 결제가 없는 지난 날만 집는다', () => {
    const all = [건({ date: '2026-08-05', time: '12:00:00' })];
    const out = 누락의심일찾기(
      all,
      '김지환',
      '9427',
      ['2026-08-05', '2026-08-06', '2026-08-18'],
      '2026-08-18'
    );
    // 8/05는 결제 있음, 8/18은 오늘이라 제외 → 8/06만 남는다
    expect(out).toEqual(['2026-08-06']);
  });

  it('2만원 넘게 쓴 날을 "결제 없음"으로 오해하지 않는다', () => {
    const all = [건({ date: '2026-08-06', time: '12:00:00', fee: '50000' })];
    const out = 누락의심일찾기(all, '김지환', '9427', ['2026-08-06'], '2026-08-18');
    expect(out).toEqual([]);
  });
});
